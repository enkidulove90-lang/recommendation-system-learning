"""Idempotent model-call gateway: the same (source, prompt, model) is
generated by a real model at most once.

Storage contract: only relative paths and hashes are recorded in SQLite; the
parsed artifact lives as a JSON file under ``data/summaries/``.  Writes are
atomic (temp file + os.replace) so a crashed run never leaves a partial JSON.
"""
from __future__ import annotations

import hashlib
import json
import os
from pathlib import Path
from typing import Any, Callable, Optional

from openai import OpenAI, APIError, Timeout, RateLimitError

from .asset_manifest import ContentAssetManifest
from config import settings


def artifact_basename(canonical_id: str, purpose: str) -> str:
    """Filesystem-safe stem for an artifact file.

    canonical ids use prefixes like ``arxiv:2601.00001``; ``:`` is illegal in
    Windows filenames, so it becomes ``__`` (double underscore, chosen so it
    cannot collide with a single ``_`` inside an id).  All consumers (gateway,
    summarizer fallback, verification script) MUST use this helper so they
    resolve the same file.
    """
    parts: list[str] = []
    for character in canonical_id:
        if character == ":":
            parts.append("__")
        elif character.isalnum() or character in ".-_":
            parts.append(character)
        else:
            parts.append("_")
    return f"{''.join(parts)}_{purpose}"


def sha256_file(path: Path) -> str:
    """Streaming SHA-256 of a file; stable regardless of file size."""
    digest = hashlib.sha256()
    with Path(path).open("rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


class ModelCallGateway:
    """Wrap one model call per idempotency key; reuse on subsequent calls."""

    def __init__(self, manifest: ContentAssetManifest, client: Any, root: Path) -> None:
        self.manifest = manifest
        self.client = client
        self.root = Path(root)

    def ensure(
        self,
        *,
        canonical_id: str,
        purpose: str,
        source: Path,
        prompt_version: str,
        model_id: str,
        build_prompt: Callable[[Path], str],
        parse_response: Callable[[str], dict[str, Any]],
    ) -> Path:
        """Return the artifact path, invoking the model only on a cache miss.

        A cache hit requires both a manifest row with the full idempotency key
        AND the artifact file still present on disk (self-healing if deleted).
        """
        source_hash = sha256_file(source)
        cached = self.manifest.lookup(
            canonical_id, purpose, source_hash, prompt_version, model_id)
        if cached is not None:
            cached_path = self.root / cached["relative_path"]
            if cached_path.is_file():
                return cached_path

        prompt = build_prompt(source)
        raw = self.client(prompt)
        parsed_data = parse_response(raw)

        # FactPack requires provenance fields that the model prompt does not
        # ask the model to invent.  Inject them from the gateway context so
        # the artifact validates against its Pydantic schema.
        if purpose == "fact_pack" and isinstance(parsed_data, dict):
            parsed_data.setdefault("canonical_id", canonical_id)
            parsed_data.setdefault("source_hash", source_hash)
            parsed_data.setdefault("model_id", model_id)
            parsed_data.setdefault("prompt_version", prompt_version)

        output = (
            self.root / "data" / "summaries"
            / f"{artifact_basename(canonical_id, purpose)}.json"
        )
        output.parent.mkdir(parents=True, exist_ok=True)
        self._write_json_atomic(output, parsed_data)

        self.manifest.record(
            canonical_id=canonical_id,
            purpose=purpose,
            relative_path=output,
            source_hash=source_hash,
            prompt_version=prompt_version,
            model_id=model_id,
            producer="model_gateway",
        )
        return output

    @staticmethod
    def _write_json_atomic(path: Path, payload: Any) -> None:
        temporary = path.with_suffix(path.suffix + ".tmp")
        temporary.write_text(
            json.dumps(payload, ensure_ascii=False, indent=2), encoding="utf-8")
        os.replace(temporary, path)


class ModelCallGatewayWithFallback(ModelCallGateway):
    """支持 SHUSHENG 优先 + DeepSeek 回退的模型调用网关"""

    def __init__(self, manifest: ContentAssetManifest, root: Path, use_shusheng_cache: bool = False):
        self.manifest = manifest
        self.root = Path(root)
        self.use_shusheng_cache = use_shusheng_cache
        # 加载缓存状态
        self._load_fallback_cache()

    def _load_fallback_cache(self):
        """加载故障回退缓存状态"""
        cache_file = self.root / ".workbuddy/model_fallback_cache.json"
        if cache_file.exists():
            try:
                with open(cache_file, "r", encoding="utf-8") as f:
                    self.fallback_cache = json.load(f)
            except:
                self.fallback_cache = {}
        else:
            self.fallback_cache = {}

    def _save_fallback_cache(self):
        """保存故障回退缓存状态"""
        cache_file = self.root / ".workbuddy/model_fallback_cache.json"
        cache_file.parent.mkdir(parents=True, exist_ok=True)
        try:
            with open(cache_file, "w", encoding="utf-8") as f:
                json.dump(self.fallback_cache, f, ensure_ascii=False, indent=2)
        except:
            pass  # 静默失败，不影响主流程

    def _has_fallback(self, purpose: str, canonical_id: str) -> bool:
        """检查是否已标记该调用的模型为回退状态"""
        key = f"{purpose}:{canonical_id}"
        return self.fallback_cache.get(key, False)

    def _set_fallback(self, purpose: str, canonical_id: str, should_fallback: bool):
        """设置该调用是否使用回退逻辑"""
        key = f"{purpose}:{canonical_id}"
        self.fallback_cache[key] = should_fallback
        self._save_fallback_cache()

    def _build_client(self, api_key: str, base_url: str) -> Optional[OpenAI]:
        """构建 OpenAI 客户端，参数验证不通过返回 None"""
        if not api_key or not base_url:
            return None
        try:
            return OpenAI(api_key=api_key, base_url=base_url)
        except Exception:
            return None

    def _call_model(self, client: OpenAI, model: str, messages: list[dict], temperature: float = 0.3, max_tokens: int = 4096) -> Optional[str]:
        """调用模型并返回内容"""
        try:
            response = client.chat.completions.create(
                model=model,
                messages=messages,
                temperature=temperature,
                max_tokens=max_tokens,
            )
            return response.choices[0].message.content or ""
        except (Timeout, RateLimitError, APIError) as e:
            return None
        except Exception as e:
            return None

    def ensure(
        self,
        *,
        canonical_id: str,
        purpose: str,
        source: Path,
        prompt_version: str,
        model_id: str,
        build_prompt: Callable[[Path], str],
        parse_response: Callable[[str], dict[str, Any]],
        use_shusheng_first: bool = True,
    ) -> Path:
        """支持故障回退的确保调用，优先使用 SHUSHENG 或指定模型，失败则回退到 DeepSeek"""
        source_hash = sha256_file(source)

        # 决定使用哪个模型 ID 进行缓存查询
        query_model_id = model_id
        if use_shusheng_first and not self._has_fallback(purpose, canonical_id):
            query_model_id = settings.SHUSHENG_MODEL

        cached = self.manifest.lookup(
            canonical_id, purpose, source_hash, prompt_version, query_model_id)
        if cached is not None:
            cached_path = self.root / cached["relative_path"]
            if cached_path.is_file():
                return cached_path

        prompt = build_prompt(source)
        raw = None

        # 优先尝试 SHUSHENG
        if use_shusheng_first and settings.SHUSHENG_API_KEY:
            client = self._build_client(
                settings.SHUSHENG_API_KEY,
                settings.SHUSHENG_API_BASE
            )
            if client:
                raw = self._call_model(
                    client,
                    settings.SHUSHENG_MODEL,
                    [{"role": "user", "content": prompt}],
                )

        # SHUSHENG 失败，尝试 DeepSeek
        if not raw and settings.DEEPSEEK_API_KEY:
            client = self._build_client(
                settings.DEEPSEEK_API_KEY,
                "https://api.deepseek.com"
            )
            if client:
                raw = self._call_model(
                    client,
                    settings.DEEPSEEK_MODEL,
                    [{"role": "user", "content": prompt}],
                )

        if not raw:
            raise RuntimeError("Model call failed: all providers failed (SHUSHENG, DeepSeek)")

        parsed_data = parse_response(raw)

        # 记录到 manifest，使用实际调用的模型 ID
        actual_model_id = settings.SHUSHENG_MODEL if raw and use_shusheng_first and settings.SHUSHENG_API_KEY else settings.DEEPSEEK_MODEL
        if actual_model_id == model_id and self._has_fallback(purpose, canonical_id):
            actual_model_id = settings.DEEPSEEK_MODEL

        # FactPack requires provenance fields that the model prompt does not
        # ask the model to invent.  Inject them from the gateway context so
        # the artifact validates against its Pydantic schema.
        if purpose == "fact_pack" and isinstance(parsed_data, dict):
            parsed_data.setdefault("canonical_id", canonical_id)
            parsed_data.setdefault("source_hash", source_hash)
            parsed_data.setdefault("model_id", actual_model_id)
            parsed_data.setdefault("prompt_version", prompt_version)

        output = (
            self.root / "data" / "summaries"
            / f"{artifact_basename(canonical_id, purpose)}.json"
        )
        output.parent.mkdir(parents=True, exist_ok=True)
        self._write_json_atomic(output, parsed_data)

        self.manifest.record(
            canonical_id=canonical_id,
            purpose=purpose,
            relative_path=output,
            source_hash=source_hash,
            prompt_version=prompt_version,
            model_id=actual_model_id,
            producer="model_gateway_with_fallback",
        )
        return output

    def mark_fallback(self, purpose: str, canonical_id: str):
        """手动标记该调用需要回退到 DeepSeek"""
        self._set_fallback(purpose, canonical_id, True)
