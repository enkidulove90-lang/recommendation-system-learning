"""The supported entry point for the Redbook creation workflow."""
from __future__ import annotations

import argparse
import json
from pathlib import Path
import sys

from redbook.application.paper_workflow import PaperCreationWorkflow
from redbook.application.evidence_pack import EvidencePackParser
from redbook.infrastructure.modelscope_vision import ModelScopeVisionReviewer
from redbook.services.figure_retrieval import FigureRetrievalService
from redbook.services.persona_composer import PersonaCatalog
from redbook.services.render_post import render_post
from redbook.services.xhs_content_gate import ContentSpecError
from redbook.infrastructure.xiaohongshu_delivery import (
    DraftPayload, OpenCliXiaohongshuDelivery, build_deliver_payload,
)
from redbook.infrastructure.delivery_errors import DeliveryError, exit_code_for, receipt_envelope
from redbook.infrastructure import run_log


def _emit_json(value: object) -> None:
    """Keep Chinese and emoji intact when launched from legacy Windows consoles."""
    payload = json.dumps(value, ensure_ascii=False, indent=2) + "\n"
    try:
        sys.stdout.write(payload)
    except UnicodeEncodeError:
        sys.stdout.buffer.write(payload.encode("utf-8"))


def main() -> None:
    parser = argparse.ArgumentParser(description="Redbook paper creation workflow")
    commands = parser.add_subparsers(dest="command", required=True)
    figures = commands.add_parser("prepare-figures", help="prefer arXiv source figures, then use high-DPI PDF fallback")
    figures.add_argument("--paper-id", required=True)
    figures.add_argument("--markdown", type=Path, required=True)
    figures.add_argument("--images", type=Path, required=True)
    figures.add_argument("--pdf", type=Path)
    figures.add_argument("--layout", type=Path)
    figures.add_argument("--arxiv-id", help="enables source-first acquisition from arxiv.org/e-print/<id>")
    figures.add_argument("--vision", action="store_true", help="use ModelScope Qwen multimodal final review")
    figures.add_argument("--data-root", type=Path, default=Path("data"))
    personas = commands.add_parser("list-personas", help="list available paper-sharing author personas")
    compose = commands.add_parser("compose-post", help="compose a draft only; never publishes to Xiaohongshu")
    compose.add_argument("--summary", type=Path, required=True, help="structured paper summary Markdown")
    compose.add_argument("--arxiv-id", required=True)
    compose.add_argument("--persona", default="research_translator")
    compose.add_argument("--github", default="")
    compose.add_argument("--title", default="", help="optional authoritative paper title")
    compose.add_argument("--output", type=Path, help="optional JSON draft path")
    evidence = commands.add_parser("parse-evidence-pack", help="parse an open-access research evidence pack with MinerU")
    evidence.add_argument("--manifest", type=Path, required=True)
    evidence.add_argument("--data-root", type=Path, default=Path("data"))
    deliver = commands.add_parser("save-xhs-draft", help="save a complete Xiaohongshu draft with real topics and a CDP PDF attachment")
    deliver.add_argument("--draft", type=Path, required=True, help="JSON generated by compose-post or the paper workflow")
    deliver.add_argument("--image", type=Path, action="append", required=True, help="high-resolution image; repeat for every page")
    deliver.add_argument("--pdf", type=Path, help="the same locally downloaded paper PDF")
    deliver.add_argument(
        "--skip-pdf-attachment", action="store_true",
        help="explicit per-run waiver for non-paper technical content; paper workflows still require a PDF",
    )
    deliver.add_argument(
        "--skip-topic-binding", action="store_true",
        help="deliver without binding real topic entities (non-paper content only); body must not contain '#'",
    )
    deliver.add_argument("--output", type=Path, help="optional delivery receipt JSON")
    note = commands.add_parser(
        "note", help="validate / stage / publish a declarative spec in redbook/notes/<paper_id>.yaml"
    )
    note.add_argument("paper_id", nargs="?", help="paper id; omit only with --list")
    note.add_argument("--list", action="store_true", help="list all note specs")
    note.add_argument("--validate", action="store_true", help="content gate only (the safe default)")
    note.add_argument("--stage", action="store_true", help="write an immutable local review package")
    note.add_argument(
        "--publish", action="store_true",
        help="deprecated alias of --save-draft; saves a draft only and never publishes publicly",
    )
    note.add_argument("--save-draft", action="store_true", help="save draft only; never publishes publicly")
    note.add_argument("--verify", action="store_true", help="read-only verify one saved draft")
    note.add_argument("--reconcile", action="store_true", help="read-only reconcile saved-draft registry records")
    note.add_argument("--draft-id", help="ASCII draft ID required by --verify")
    note.add_argument("--data-root", type=Path, default=Path("data"))
    note.add_argument("--notes-dir", type=Path, help="override redbook/notes for tests")
    orchestrate = commands.add_parser(
        "orchestrate", help="queue/worker operations: enqueue, status, cancel, drain"
    )
    orchestrate.add_argument("action", choices=["enqueue", "status", "cancel", "drain"])
    orchestrate.add_argument("--queue", default="intake")
    orchestrate.add_argument("--payload-ref", help="addressing reference, e.g. note:<paper_id>")
    orchestrate.add_argument("--job-id")
    orchestrate.add_argument("--handler", default="noop", help="noop | save_draft")
    orchestrate.add_argument("--data-root", type=Path, default=Path("data"))
    orchestrate.add_argument("--notes-dir", type=Path, help="override redbook/notes for tests")

    sentinel = commands.add_parser(
        "sentinel", help="dependency probe sweep, 11:00 retrieval, pool dispatch"
    )
    sentinel.add_argument("action", choices=["run-once", "probe", "pool"])
    sentinel.add_argument("--data-root", type=Path, default=Path("data"))
    sentinel.add_argument("--no-dispatch", action="store_true",
                          help="pool-only mode: skip queue dispatch")
    sentinel.add_argument("--export-pending", action="store_true",
                          help="with sentinel pool, emit the read-only external-consumer contract")
    sentinel.add_argument("--reconcile", action="store_true",
                          help="with sentinel pool, show the read-only pool/registry progress view")
    sentinel.add_argument("--platform", choices=("homepage", "xiaohongshu", "wechat"),
                          help="independent platform consumer; defaults to sentinel.yaml")

    args = parser.parse_args()
    if args.command == "prepare-figures":
        reviewer = ModelScopeVisionReviewer() if args.vision else None
        service = FigureRetrievalService(reviewer=reviewer)
        workflow = PaperCreationWorkflow(args.data_root, figures=service)
        result = workflow.prepare_figures(
            args.paper_id, args.markdown, args.images, args.pdf, args.layout, args.vision, args.arxiv_id
        )
        _emit_json(result.as_dict())
    elif args.command == "list-personas":
        _emit_json([
            {"id": item.id, "name": item.name, "audience": item.audience, "topics": item.topics,
             "strategy": item.strategy}
            for item in PersonaCatalog().list()
        ])
    elif args.command == "compose-post":
        # 统一内容生产入口：不再自行组装正文，改由 render_post 生成并过发布闸门。
        # 输出仍保留 title/body/topics，兼容 save-xhs-draft --draft 的读取契约。
        try:
            result = render_post(
                "xhs", args.summary.read_text(encoding="utf-8"), None,
                arxiv_id=args.arxiv_id, persona_id=args.persona,
                github_url=args.github, paper_title=args.title,
            )
        except ContentSpecError as error:
            _emit_json({"error": str(error)})
            raise SystemExit(2) from error
        if args.output:
            args.output.parent.mkdir(parents=True, exist_ok=True)
            args.output.write_text(json.dumps(result, ensure_ascii=False, indent=2), encoding="utf-8")
        _emit_json(result)
    elif args.command == "parse-evidence-pack":
        _emit_json(EvidencePackParser(args.data_root).parse(args.manifest))
    elif args.command == "save-xhs-draft":
        try:
            payload = build_deliver_payload(args)
        except ValueError as error:
            _emit_json({"error": str(error)})
            raise SystemExit(2) from error
        try:
            receipt = OpenCliXiaohongshuDelivery().deliver(payload)
        except DeliveryError as error:
            value = receipt_envelope(error, state="failed")
            if args.output:
                args.output.parent.mkdir(parents=True, exist_ok=True)
                args.output.write_text(json.dumps(value, ensure_ascii=False, indent=2), encoding="utf-8")
            _emit_json(value)
            raise SystemExit(exit_code_for(error.code)) from error
        value = {
            "draft_id": receipt.draft_id, "title": receipt.title, "image_count": receipt.image_count,
            "topics": list(receipt.topics), "pdf_attachment": receipt.pdf_name, "state": "saved_draft_only",
        }
        if args.output:
            args.output.parent.mkdir(parents=True, exist_ok=True)
            args.output.write_text(json.dumps(value, ensure_ascii=False, indent=2), encoding="utf-8")
        _emit_json(value)
    elif args.command == "note":
        from redbook.services.note_spec import list_notes

        if args.list:
            _emit_json(list_notes(args.notes_dir))
            return
        if not args.paper_id and not args.reconcile:
            parser.error("note requires <paper_id> (or --list)")
        selected = sum(bool(value) for value in (
            args.validate, args.stage, args.publish, args.save_draft, args.verify, args.reconcile,
        ))
        if selected > 1:
            parser.error("note accepts exactly one action flag")
        action = (
            "reconcile" if args.reconcile else "verify" if args.verify else
            "save_draft" if args.save_draft else "publish" if args.publish else
            "stage" if args.stage else "validate"
        )
        if args.draft_id and not args.verify:
            parser.error("--draft-id is only valid with --verify")
        if args.verify and not args.draft_id:
            parser.error("--verify requires --draft-id")
        if args.reconcile:
            from redbook.orchestration.reconcile import (
                list_orphan_candidates,
                reconcile_stale_saves,
                reconcile_uncertain_deliveries,
                reconcile_verified_deliveries,
            )
            from redbook.orchestration.registry import SqliteDeliveryRegistry

            registry = SqliteDeliveryRegistry(args.data_root / "state" / "orchestration.sqlite")
            delivery = OpenCliXiaohongshuDelivery()
            try:
                delivery.opencli.preflight()
                drafts = delivery._drafts()
            except DeliveryError as error:
                _emit_json(receipt_envelope(error, state="failed"))
                raise SystemExit(exit_code_for(error.code)) from error
            draft_ids = {str(item.get("id")) for item in drafts if item.get("id")}
            result = {
                "ok": True,
                "results": [
                    {"stale_saves": reconcile_stale_saves(
                        registry, stale_after_seconds=300,
                        find_draft=lambda entry: str(entry["draft_id"])
                        if entry.get("draft_id") in draft_ids else None,
                    )},
                    {"verified_deliveries": reconcile_verified_deliveries(
                        registry, draft_exists=lambda entry: str(entry.get("draft_id")) in draft_ids,
                    )},
                    {"uncertain_deliveries": reconcile_uncertain_deliveries(
                        registry, verify=lambda _entry: "uncertain", rollback=lambda _entry: False,
                    )},
                ],
                "orphans": list_orphan_candidates(registry, drafts_client=lambda: drafts),
            }
        else:
            workflow = PaperCreationWorkflow(args.data_root)
            if args.verify:
                result = workflow.verify_note(args.paper_id, args.draft_id, notes_dir=args.notes_dir)
            elif args.publish or args.save_draft:
                result = workflow.publish_note(args.paper_id, notes_dir=args.notes_dir)
            elif args.stage:
                result = workflow.stage_note(args.paper_id, notes_dir=args.notes_dir)
            else:
                result = workflow.validate_note(args.paper_id, notes_dir=args.notes_dir)
        run_log.log_event(
            "note",
            action=action,
            paper_id=args.paper_id,
            ok=bool(result.get("ok")),
            status="ok" if result.get("ok") else "failed",
        )
        if not result.get("ok"):
            error_code = result.get("error_code")
            if error_code:
                details = result.get("error_details")
                error = DeliveryError(
                    str(result.get("error", "note action failed")),
                    str(error_code),
                    details if isinstance(details, dict) else None,
                )
                _emit_json(receipt_envelope(error, state="failed"))
                raise SystemExit(exit_code_for(error.code))
            _emit_json(result)
            raise SystemExit(2)
        _emit_json(result)
    elif args.command == "orchestrate":
        from redbook.orchestration.queue import QueueFullError, SqliteQueueBackend
        from redbook.orchestration.worker import HANDLERS, Worker

        backend = SqliteQueueBackend(args.data_root / "state" / "orchestration.sqlite")
        if args.action == "enqueue":
            if not args.payload_ref:
                parser.error("orchestrate enqueue requires --payload-ref")
            try:
                job = backend.enqueue(args.queue, args.payload_ref)
            except QueueFullError as error:
                _emit_json(receipt_envelope(error, state="rejected"))
                raise SystemExit(exit_code_for(error.code)) from error
            _emit_json(job.to_dict() | {"ok": True})
        elif args.action == "status":
            job = backend.get_job(args.job_id or "")
            if job is None:
                _emit_json({"ok": False, "error": "job not found"})
                raise SystemExit(2)
            _emit_json(job.to_dict() | {"ok": True, "events": backend.events(job.job_id)})
        elif args.action == "cancel":
            _emit_json({"ok": backend.cancel(args.job_id or ""), "job_id": args.job_id})
        else:  # drain
            if args.handler not in HANDLERS:
                parser.error(f"unknown handler {args.handler!r}")
            worker = Worker(backend)
            receipts = worker.drain(HANDLERS[args.handler])
            _emit_json({"ok": True, "processed": [receipt.to_dict() for receipt in receipts]})
    elif args.command == "sentinel":
        import yaml as _yaml

        from redbook.orchestration.queue import SqliteQueueBackend
        from redbook.sentinel.paper_pool import PaperPool
        from redbook.sentinel.probes import build_default_probes
        from redbook.sentinel.runner import DailyDiscoveryAdapter, SentinelRunner

        config_path = Path(__file__).resolve().parent / "config" / "sentinel.yaml"
        config = _yaml.safe_load(config_path.read_text(encoding="utf-8")) \
            if config_path.exists() else {}
        daily_config = Path(str(config.get("daily_discovery_config", "daily_draft.yaml")))
        if not daily_config.is_absolute():
            daily_config = config_path.parent / daily_config
        pool = PaperPool(args.data_root / "state" / "orchestration.sqlite")
        runner = SentinelRunner(pool, config=config,
                                probes=build_default_probes(config),
                                log_dir=args.data_root / "logs",
                                discovery=DailyDiscoveryAdapter(args.data_root, daily_config),
                                platform=args.platform or str(config.get("platform", "homepage")))
        if args.action == "probe":
            results = runner.probe_all()
            _emit_json({"ok": True, "probes": [r.to_dict() for r in results]})
        elif args.action == "pool":
            if args.reconcile:
                from redbook.orchestration.registry import SqliteDeliveryRegistry
                registry = SqliteDeliveryRegistry(args.data_root / "state" / "orchestration.sqlite")
                entries = registry.pool_delivery_view()
                _emit_json({"ok": True, "count": len(entries), "entries": entries})
                return
            if args.export_pending:
                _emit_json({
                    "ok": True,
                    "schema_version": "paper-pool-export/v1",
                    "entries": pool.export_pending_candidates(),
                })
                return
            with pool._connection() as connection:
                rows = [dict(row) for row in connection.execute(
                    "SELECT canonical_id, arxiv_id, title, status, "
                    "pending_delivery, platforms, discovered_at FROM paper_pool "
                    "ORDER BY discovered_at").fetchall()]
            _emit_json({"ok": True, "count": len(rows), "entries": rows})
        else:  # run-once: Task Scheduler entry point
            queue = None if args.no_dispatch else \
                SqliteQueueBackend(args.data_root / "state" / "orchestration.sqlite")
            _emit_json(runner.run_once(queue, dispatch=queue is not None))


if __name__ == "__main__":
    main()
